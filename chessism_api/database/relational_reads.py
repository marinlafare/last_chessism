"""Player-scoped reads without expanding the wide compatibility views.

Only explicitly opted-in sessions use this path. Ownership still comes from
game_player (including both sides of self-play), not an inferred game count.
Select only the game attributes a caller needs; do not join opponent/player
names or the mode dictionary for queries that never use them.
"""
from sqlalchemy import text

from .relational_storage import storage_for


def player_rows_sql(session, query, fields):
    layout = storage_for(session)
    if layout is None:
        return text(str(query))
    expressions = {
        'player_name': 'CAST(:player AS varchar)',
        'link': 'gp.game_link',
        'color': "CASE WHEN gp.is_white THEN 'white' ELSE 'black' END",
        'played_at': 'g.played_at',
        'n_moves': 'g.n_moves',
        'rating': 'CASE WHEN gp.is_white THEN g.white_elo ELSE g.black_elo END',
        'opponent_rating': 'CASE WHEN gp.is_white THEN g.black_elo ELSE g.white_elo END',
        'result': 'CASE WHEN gp.is_white THEN g.white_result ELSE g.black_result END',
        'end_by': 'CASE WHEN gp.is_white THEN g.white_str_result ELSE g.black_str_result END',
        'mode': 'm.name',
        'eco': 'g.eco',
        'opponent_name': 'opponent.player_name',
    }
    selected = tuple(dict.fromkeys(('player_name', *fields)))
    if set(selected) - expressions.keys():
        raise ValueError('Unknown normalized player-read field')
    joins = ''
    if set(selected) - {'player_name', 'link', 'color'}:
        joins += f" JOIN {layout.table('game')} g ON g.link=gp.game_link"
    if 'mode' in selected:
        joins += f" LEFT JOIN {layout.table('game_mode')} m ON m.id=g.mode_id"
    if 'opponent_name' in selected:
        joins += f""" LEFT JOIN {layout.table('player')} opponent
            ON opponent.id=CASE WHEN gp.is_white THEN g.black_player_id ELSE g.white_player_id END"""
    projection = ','.join(expressions[field] + ' AS ' + field for field in selected)
    prefix = f"""WITH game_player AS NOT MATERIALIZED (
        SELECT {projection} FROM {layout.table('game_player')} gp {joins}
        WHERE gp.player_id=(SELECT id FROM {layout.table('player')} WHERE player_name=:player)
    )"""
    statement = str(query).lstrip()
    # The caller SQL is static application code; do not rewrite arbitrary SQL
    # identifiers, values, ORDER BY rules, or filter/limit semantics.
    if statement.upper().startswith('WITH '):
        return text(prefix + ',' + statement[5:])
    return text(prefix + ' ' + statement)


def player_ratings_sql(session, legacy_query, *, local_timestamp_sql):
    """Reduce to the last game per local day before decoding mode names.

    The generic compatibility projection lets the mode-name sort drive a
    nested loop over the player's whole history. Instead resolve eligible mode
    IDs once, filter first, and rank narrow numeric rows. Materializing this
    bounded player selection also computes the local date only once per row.
    No application response or timezone/date-boundary semantics change.
    """
    layout = storage_for(session)
    if layout is None:
        return text(str(legacy_query))
    # Separate sides expose the existing player/mode/date indexes. UNION ALL
    # preserves both perspectives of self-play. Verify the actual association
    # AFTER filtering; never replace recorded ownership with inferred rows.
    branches=[]
    for side,flag in (('black','false'),('white','true')):
        branches.append(f"""
            SELECT g.link, {flag} AS is_white, g.mode_id, g.played_at, g.{side}_elo AS rating
            FROM {layout.table('game')} g
            WHERE g.{side}_player_id=(SELECT id FROM owner)
              AND g.mode_id = ANY(ARRAY(SELECT id FROM modes))
              AND g.played_at IS NOT NULL
              AND (CAST(:date_from_utc AS timestamptz) IS NULL OR g.played_at >= CAST(:date_from_utc AS timestamptz))
              AND (CAST(:date_to_utc AS timestamptz) IS NULL OR g.played_at < CAST(:date_to_utc AS timestamptz))
        """)
    # local_timestamp_sql is generated by the application's existing timezone
    # helper with alias g, never supplied by a request.
    return text(f"""
        WITH owner AS MATERIALIZED (
            SELECT id FROM {layout.table('player')} WHERE player_name=:player
        ), modes AS MATERIALIZED (
            SELECT id, name FROM {layout.table('game_mode')}
            WHERE name IN ('bullet', 'blitz', 'rapid') AND (:mode='all' OR name=:mode)
        ), candidates AS MATERIALIZED (
            {' UNION ALL '.join(branches)}
        ), eligible AS MATERIALIZED (
            SELECT g.*, ({local_timestamp_sql})::date AS local_date
            FROM candidates g
            WHERE EXISTS (
                SELECT 1 FROM {layout.table('game_player')} gp
                WHERE gp.game_link=g.link AND gp.is_white=g.is_white
                  AND gp.player_id=(SELECT id FROM owner)
            )
        ), daily AS (
            SELECT DISTINCT ON (mode_id, local_date)
                mode_id, rating, link, played_at, local_date
            FROM eligible
            ORDER BY mode_id, local_date, played_at DESC, link DESC, is_white ASC
        )
        SELECT m.name AS mode, d.rating, d.link, d.played_at, d.local_date
        FROM daily d JOIN modes m ON m.id=d.mode_id
        ORDER BY m.name, d.local_date
    """)
