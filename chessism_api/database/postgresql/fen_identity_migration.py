"""Explicit offline migration. Never called from application startup.

The numeric table is copied and checked before an atomic rename. The original
text table remains as fen_continuation_legacy_text until a separately verified
post-migration backup exists. No DROP TABLE or backup expiry is performed here.
"""
from .fen_identity import SHAPE_SQL, schema_version, validate_identity

MIGRATION_LOCK = 731_946_205
LEGACY = 'fen_continuation_legacy_text'


async def relation_sizes(connection):
    rows = await connection.fetch("""
      SELECT c.relname AS name, pg_table_size(c.oid) AS table_bytes,
             pg_indexes_size(c.oid) AS index_bytes, pg_total_relation_size(c.oid) AS total_bytes
      FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname=current_schema() AND c.relname IN ('fen','fen_continuation','fen_continuation_legacy_text')
    """)
    return [dict(row) for row in rows]


async def compare_continuations(connection, original, replacement):
    if original not in ('fen_continuation', LEGACY) or replacement not in ('fen_continuation_numeric_v2', 'fen_continuation'):
        raise ValueError('Unexpected migration relation')
    old_count = await connection.fetchval(f'SELECT count(*) FROM {original}')
    new_count = await connection.fetchval(f'SELECT count(*) FROM {replacement}')
    mismatches = await connection.fetchval(f"""
      SELECT count(*) FROM {original} old
      LEFT JOIN fen f ON f.fen=old.fen_fen
      LEFT JOIN {replacement} new ON new.id=old.id
      WHERE new.id IS NULL OR f.fen_id IS NULL OR
        ROW(new.fen_id,new.rank,new.move,new.score)
        IS DISTINCT FROM ROW(f.fen_id,old.rank,old.move,old.score)
    """)
    if old_count != new_count or mismatches:
        raise RuntimeError(f'Continuation verification failed: old={old_count}, new={new_count}, mismatches={mismatches}')
    return {'original_rows': old_count, 'numeric_rows': new_count, 'mismatches': mismatches}


async def migrate(connection, publish):
    """Caller provides a maintenance window, verified backup and isolated test."""
    if not await connection.fetchval('SELECT pg_try_advisory_lock($1)', MIGRATION_LOCK):
        raise RuntimeError('Database schema maintenance is already active')
    try:
        await connection.execute("SET lock_timeout='5s'")
        await connection.execute("SET statement_timeout='2h'")
        await connection.execute("SET work_mem='64MB'")
        await connection.execute("SET maintenance_work_mem='256MB'")
        await connection.execute("SET max_parallel_workers_per_gather=2")
        await connection.execute("SET application_name='chessism-fen-identity-migration'")
        shape = schema_version(await connection.fetch(SHAPE_SQL))
        if shape == 'numeric_v2':
            return {'already_migrated': True, 'identity': await validate_identity(connection)}
        if await connection.fetchval("SELECT to_regclass('fen_continuation_legacy_text') IS NOT NULL OR to_regclass('fen_continuation_numeric_v2') IS NOT NULL"):
            raise RuntimeError('An unexpected migration table exists; inspect it before proceeding')
        if not await connection.fetchval("SELECT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='fen_continuation'::regclass AND attname='fen_fen' AND NOT attisdropped)"):
            raise RuntimeError('Expected original continuation schema was not found')
        # A rename must not silently strand dependent views, grants, triggers,
        # row-security policies or foreign keys on the legacy relation.
        dependencies = await connection.fetchval("""
          SELECT EXISTS(SELECT 1 FROM pg_constraint WHERE confrelid='fen_continuation'::regclass AND contype='f')
             OR EXISTS(SELECT 1 FROM pg_trigger WHERE tgrelid='fen_continuation'::regclass AND NOT tgisinternal)
             OR EXISTS(SELECT 1 FROM pg_depend d JOIN pg_rewrite r ON r.oid=d.objid
                       WHERE d.refobjid='fen_continuation'::regclass AND d.classid='pg_rewrite'::regclass)
             OR EXISTS(SELECT 1 FROM pg_class WHERE oid='fen_continuation'::regclass AND (relacl IS NOT NULL OR relrowsecurity))
        """)
        if dependencies:
            raise RuntimeError('Continuation dependencies require a reviewed migration strategy')
        before = await relation_sizes(connection)
        await publish('counting_original_positions', sizes_before=before)
        fen_count = await connection.fetchval('SELECT count(*) FROM fen')
        has_identifier = await connection.fetchval("SELECT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='fen'::regclass AND attname='fen_id' AND NOT attisdropped)")
        if not has_identifier:
            await publish('adding_fen_identifiers', fen_count=fen_count)
            async with connection.transaction():
                await connection.execute('ALTER TABLE fen ADD COLUMN fen_id BIGINT GENERATED BY DEFAULT AS IDENTITY')
                await connection.execute('ALTER TABLE fen ADD CONSTRAINT uq_fen_fen_id UNIQUE (fen_id)')
        else:
            parent = [r for r in await connection.fetch(SHAPE_SQL) if r['table_name']=='fen' and r['column_name']=='fen_id']
            if not parent or parent[0]['data_type'] != 'bigint' or parent[0]['identity_kind'] not in ('a','d'):
                raise RuntimeError('Existing FEN identifier is not a compatible identity')
        await publish('copying_continuations')
        # This transaction is all-or-nothing. Failure leaves the original text
        # table active; the additive parent identity is safe to retain/reuse.
        async with connection.transaction():
            await connection.execute('LOCK TABLE fen IN SHARE MODE')
            await connection.execute('LOCK TABLE fen_continuation IN ACCESS EXCLUSIVE MODE')
            await connection.execute("""
              CREATE TABLE fen_continuation_numeric_v2 (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY,
                fen_id BIGINT NOT NULL, rank INTEGER NOT NULL,
                move VARCHAR NOT NULL, score DOUBLE PRECISION NOT NULL
              )
            """)
            await connection.execute("""
              INSERT INTO fen_continuation_numeric_v2 (id,fen_id,rank,move,score)
              SELECT c.id,f.fen_id,c.rank,c.move,c.score
              FROM fen_continuation c JOIN fen f ON f.fen=c.fen_fen
            """)
            await publish('indexing_numeric_continuations')
            await connection.execute('ALTER TABLE fen_continuation_numeric_v2 ADD CONSTRAINT fen_continuation_numeric_pkey PRIMARY KEY (id)')
            await connection.execute('ALTER TABLE fen_continuation_numeric_v2 ADD CONSTRAINT uq_fen_continuation_fen_id_rank UNIQUE (fen_id,rank)')
            await connection.execute('ALTER TABLE fen_continuation_numeric_v2 ADD CONSTRAINT fk_fen_continuation_fen_id FOREIGN KEY (fen_id) REFERENCES fen(fen_id) NOT VALID')
            await connection.execute('ALTER TABLE fen_continuation_numeric_v2 VALIDATE CONSTRAINT fk_fen_continuation_fen_id')
            await connection.execute("SELECT setval(pg_get_serial_sequence('fen_continuation_numeric_v2','id'), COALESCE(max(id),1), count(*)>0) FROM fen_continuation_numeric_v2")
            await connection.execute('ANALYZE fen_continuation_numeric_v2')
            await publish('verifying_every_continuation')
            comparison = await compare_continuations(connection, 'fen_continuation', 'fen_continuation_numeric_v2')
            after_count = await connection.fetchval('SELECT count(*) FROM fen')
            if after_count != fen_count:
                raise RuntimeError('Position count changed during maintenance')
            await publish('switching_tables', comparison=comparison)
            await connection.execute('ALTER TABLE fen_continuation RENAME TO fen_continuation_legacy_text')
            await connection.execute('ALTER TABLE fen_continuation_numeric_v2 RENAME TO fen_continuation')
            identity = await validate_identity(connection)
        await publish('analyzing_statistics')
        await connection.execute('ANALYZE fen (fen_id)')
        return {'fen_count': fen_count, 'comparison': comparison, 'identity': identity,
                'sizes_before': before, 'sizes_after': await relation_sizes(connection),
                'legacy_table_retained': LEGACY}
    finally:
        await connection.execute('SELECT pg_advisory_unlock($1)', MIGRATION_LOCK)
