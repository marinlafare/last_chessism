"""Destructive fixtures run ONLY in the explicitly named isolated test DB."""
import os
import unittest
from unittest.mock import AsyncMock
from uuid import uuid4

import asyncpg
from chessism_api.database.fen_reference_identity import validate_references
from chessism_api.database.fen_reference_migration import migrate, compare, TABLES, LEGACY

URL = os.getenv('CHESSISM_FEN_ID_TEST_URL','')


@unittest.skipUnless(URL, 'requires isolated chessism_fen_id_test database')
class ReferenceMigrationTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        if not URL.endswith('/chessism_fen_id_test'):
            raise RuntimeError('Refusing non-test database')
        self.conn = await asyncpg.connect(URL)
        self.schema = 'fen_ref_test_' + uuid4().hex
        await self.conn.execute(f'CREATE SCHEMA "{self.schema}"')
        await self.conn.execute(f'SET search_path="{self.schema}"')
        await self.conn.execute("""
            CREATE TABLE fen (fen VARCHAR PRIMARY KEY,fen_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                CONSTRAINT uq_fen_fen_id UNIQUE(fen_id));
            CREATE TABLE fen_continuation (id SERIAL PRIMARY KEY,fen_id BIGINT NOT NULL,
                rank INTEGER NOT NULL,CONSTRAINT uq_fen_continuation_fen_id_rank UNIQUE(fen_id,rank),
                CONSTRAINT fk_fen_continuation_fen_id FOREIGN KEY(fen_id) REFERENCES fen(fen_id));
            CREATE TABLE game (link BIGINT PRIMARY KEY);
            CREATE TABLE player (player_name VARCHAR PRIMARY KEY);
            CREATE TABLE game_fen_association (id SERIAL PRIMARY KEY,game_link BIGINT NOT NULL REFERENCES game(link),
                fen_fen VARCHAR NOT NULL REFERENCES fen(fen),n_move INTEGER NOT NULL,move_color VARCHAR(5) NOT NULL,
                CONSTRAINT _game_fen_move_color_uc UNIQUE(game_link,fen_fen,n_move,move_color));
            CREATE INDEX ix_game_fen_association_fen_fen ON game_fen_association(fen_fen);
            CREATE INDEX ix_game_fen_association_game_link ON game_fen_association(game_link);
            CREATE INDEX ix_game_fen_association_game_order ON game_fen_association(game_link,n_move,move_color);
            CREATE TABLE player_position_frequency (player_name VARCHAR REFERENCES player(player_name) ON DELETE CASCADE,
                player_color VARCHAR(5),fen_fen VARCHAR REFERENCES fen(fen) ON DELETE CASCADE,
                games_with_position BIGINT NOT NULL,total_occurrences BIGINT NOT NULL,
                PRIMARY KEY(player_name,player_color,fen_fen),
                CONSTRAINT player_position_frequency_color CHECK(player_color IN ('white','black')),
                CONSTRAINT player_position_frequency_games_positive CHECK(games_with_position>1),
                CONSTRAINT player_position_frequency_occurrences_valid CHECK(total_occurrences>=games_with_position));
            INSERT INTO fen(fen) VALUES ('a'),('b');
            INSERT INTO game VALUES(1),(2);
            INSERT INTO player VALUES('p');
            INSERT INTO game_fen_association(id,game_link,fen_fen,n_move,move_color)
                VALUES(10,1,'a',1,'white'),(14,1,'a',3,'white'),(20,2,'a',1,'black'),(23,2,'b',2,'white');
            SELECT setval(pg_get_serial_sequence('game_fen_association','id'),100,true);
            INSERT INTO player_position_frequency VALUES('p','white','a',2,3);
            CREATE TABLE home_summary_source(id INT PRIMARY KEY,revision BIGINT);
            INSERT INTO home_summary_source VALUES(1,1);
            CREATE FUNCTION invalidate_home_summary_v1() RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN UPDATE home_summary_source SET revision=revision+1 WHERE id=1; RETURN NULL; END $$;
            CREATE TRIGGER home_summary_v1_game_fen_association_rows AFTER INSERT OR DELETE OR TRUNCATE
                ON game_fen_association FOR EACH STATEMENT EXECUTE FUNCTION invalidate_home_summary_v1();
            CREATE TRIGGER home_summary_v1_game_fen_association_values AFTER UPDATE OF game_link,fen_fen
                ON game_fen_association FOR EACH STATEMENT EXECUTE FUNCTION invalidate_home_summary_v1();
        """)

    async def asyncTearDown(self):
        await self.conn.execute('SET search_path=public')
        await self.conn.execute(f'DROP SCHEMA "{self.schema}" CASCADE')
        await self.conn.close()

    async def test_exact_copy_constraints_sequence_triggers_and_retry(self):
        self.assertEqual((await validate_references(self.conn,allow_legacy=True))['version'],'text_v1')
        result=await migrate(self.conn,AsyncMock())
        self.assertEqual(result['comparison'][TABLES[0]],{'original_rows':4,'numeric_rows':4,'mismatches':0})
        self.assertEqual(result['comparison'][TABLES[1]],{'original_rows':1,'numeric_rows':1,'mismatches':0})
        self.assertEqual(result['homepage_triggers_preserved'],2)
        self.assertEqual(await self.conn.fetchval('SELECT revision FROM home_summary_source'),1)
        new_id=await self.conn.fetchval("INSERT INTO game_fen_association(game_link,fen_id,n_move,move_color) SELECT 1,fen_id,4,'white' FROM fen WHERE fen='a' RETURNING id")
        self.assertGreater(new_id,100)
        self.assertEqual(await self.conn.fetchval('SELECT revision FROM home_summary_source'),2)
        await self.conn.execute("UPDATE game_fen_association SET fen_id=(SELECT fen_id FROM fen WHERE fen='b') WHERE id=$1",new_id)
        self.assertEqual(await self.conn.fetchval('SELECT revision FROM home_summary_source'),3)
        with self.assertRaises(asyncpg.ForeignKeyViolationError):
            await self.conn.execute("INSERT INTO game_fen_association(game_link,fen_id,n_move,move_color) VALUES(1,999,4,'white')")
        with self.assertRaises(asyncpg.UniqueViolationError):
            await self.conn.execute("INSERT INTO game_fen_association(game_link,fen_id,n_move,move_color) SELECT game_link,fen_id,n_move,move_color FROM game_fen_association WHERE id=10")
        with self.assertRaises(asyncpg.CheckViolationError):
            await self.conn.execute('UPDATE player_position_frequency SET games_with_position=1')
        self.assertTrue((await migrate(self.conn,AsyncMock()))['already_migrated'])
        # Legacy tables cannot block real deletions or change via cascades.
        await self.conn.execute('DELETE FROM game_fen_association WHERE game_link=1; DELETE FROM game WHERE link=1')
        await self.conn.execute("DELETE FROM player WHERE player_name='p'")
        self.assertEqual(await self.conn.fetchval('SELECT count(*) FROM player_position_frequency'),0)
        self.assertEqual(await self.conn.fetchval('SELECT count(*) FROM player_position_frequency_legacy_text'),1)
        self.assertEqual(await self.conn.fetchval('SELECT count(*) FROM game_fen_association_legacy_text'),4)

    async def test_interruption_after_swap_rolls_back_both_tables_and_triggers(self):
        async def fail(phase,**_):
            if phase=='checking_numeric_reference_identity': raise RuntimeError('injected')
        with self.assertRaisesRegex(RuntimeError,'injected'):
            await migrate(self.conn,fail)
        self.assertEqual((await validate_references(self.conn,allow_legacy=True))['version'],'text_v1')
        for table in TABLES:
            self.assertIsNone(await self.conn.fetchval('SELECT to_regclass($1)',LEGACY[table]))
        await self.conn.execute("UPDATE game_fen_association SET fen_fen='b' WHERE id=10")
        self.assertEqual(await self.conn.fetchval('SELECT revision FROM home_summary_source'),2)
        self.assertEqual((await migrate(self.conn,AsyncMock()))['identity']['version'],'numeric_v1')

    async def test_corruption_detected_for_each_table(self):
        await migrate(self.conn,AsyncMock())
        await self.conn.execute('UPDATE game_fen_association SET n_move=999 WHERE id=10')
        with self.assertRaisesRegex(RuntimeError,'verification failed'):
            await compare(self.conn,TABLES[0],LEGACY[TABLES[0]],TABLES[0])
        await self.conn.execute('UPDATE player_position_frequency SET total_occurrences=999')
        with self.assertRaisesRegex(RuntimeError,'verification failed'):
            await compare(self.conn,TABLES[1],LEGACY[TABLES[1]],TABLES[1])

    async def test_missing_parent_is_not_silently_dropped(self):
        await self.conn.execute('ALTER TABLE game_fen_association DROP CONSTRAINT game_fen_association_fen_fen_fkey')
        await self.conn.execute("UPDATE game_fen_association SET fen_fen='missing' WHERE id=10")
        with self.assertRaisesRegex(RuntimeError,'verification failed'):
            await migrate(self.conn,AsyncMock())
        self.assertEqual(await self.conn.fetchval('SELECT count(*) FROM game_fen_association'),4)

    async def test_external_dependencies_fail_closed(self):
        await self.conn.execute('CREATE VIEW frequency_view AS SELECT * FROM player_position_frequency')
        with self.assertRaisesRegex(RuntimeError,'dependencies'):
            await migrate(self.conn,AsyncMock())

    async def test_additional_constraints_are_not_silently_lost(self):
        await self.conn.execute('ALTER TABLE game_fen_association ADD CONSTRAINT custom_moves CHECK(n_move>0)')
        with self.assertRaisesRegex(RuntimeError,'Additional constraints'):
            await migrate(self.conn,AsyncMock())

    async def test_empty_tables_and_sequence_guard(self):
        await self.conn.execute('DELETE FROM game_fen_association; DELETE FROM player_position_frequency')
        result=await migrate(self.conn,AsyncMock())
        self.assertEqual(result['comparison'][TABLES[0]]['numeric_rows'],0)
        await self.conn.execute("INSERT INTO game_fen_association(id,game_link,fen_id,n_move,move_color) VALUES(101,1,1,1,'white')")
        with self.assertRaisesRegex(RuntimeError,'sequence'):
            await validate_references(self.conn)


if __name__=='__main__': unittest.main()
