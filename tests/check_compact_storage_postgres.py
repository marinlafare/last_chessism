async def exercise(socket, conn):
    from chessism_api.database import db_interface
    from chessism_api.database.db_interface import DBInterface
    from chessism_api.operations.compact_writes import insert_associations
    from chessism_api.operations.compact_summaries import refresh_mode_summary
    from chessism_api.operations.fen_results import stage_fen_results
    from chessism_api.operations.fen_backup import database as fen_backup
    from chessism_api.operations.ingestion_pipeline.game_repository import _sync_player_month_counts
    from chessism_api.operations.tablebase import _save_tablebase_batch
    layout=RelationalStorage('public','chessism_archive','chessism_reads','relational_v3')
    engine=create_async_engine(URL.create('postgresql+asyncpg',username='chessism_user',
        host=str(socket),port=55432,database='chessism_db'),
        connect_args={'server_settings':{'search_path':layout.search_path}})
    factory=async_sessionmaker(engine,expire_on_commit=False,info={SESSION_KEY:layout})
    try:
        async with engine.connect() as connection:
            await require_compact_contract(connection,layout)
        async def association(fen):
            async with factory.begin() as session:
                await insert_associations(session,[{'game_link':101,'fen_id':fen,'n_move':1,'move_color':'white'}])
        await asyncio.gather(association(1),association(1))
        try:
            await association(2)
            raise AssertionError('Conflicting association accepted')
        except ValueError:
            pass
        assert await conn.fetchval('SELECT count(*) FROM game_fen_association')==1
        with patch.object(db_interface,'AsyncDBSession',factory), patch.object(fen_backup,'AsyncDBSession',factory):
            association_row=await DBInterface(GameFenAssociation).create(
                {'game_link':101,'fen_id':1,'n_move':1,'move_color':'white'})
            assert association_row['id']==await conn.fetchval('SELECT id FROM game_fen_association')
            stats=DBInterface(PlayerStats)
            previous_updated=await conn.fetchval("SELECT last_updated FROM player_stats WHERE player_id=1")
            updated=await stats.update('white',{'chess_blitz_last_rating':2010})
            assert updated['player_name']=='white' and updated['chess_blitz_last_rating']==2010
            assert updated['last_updated']>previous_updated
            assert (await stats.update('white',{}))['last_updated']==updated['last_updated']
            assert await stats.update('absent',{}) is None
            assert (await stats.read(player_name='white'))[0]['chess_blitz_last_rating']==2010
            created=await stats.create({'player_name':'black','chess_blitz_last_rating':1900})
            assert created['player_name']=='black'
            await stats.delete('black')
            async with factory.begin() as session:
                await _sync_player_month_counts(session,'white',{(2026,1),(2026,2)})
                assert (await refresh_mode_summary(session,['white']))['total']==1
                await stage_fen_results(session,[{'fen':'test-fen-a','score':20.0,'next_moves':'e2e4',
                    'wdl_win':2.0,'wdl_draw':998.0,'wdl_loss':0.0}],
                    [{'fen_fen':'test-fen-a','rank':2,'move':'d2d4','score':11.0}],fen_ids={'test-fen-a':1})
            assert await conn.fetchval("SELECT score FROM fen WHERE fen_id=1")==20
            async with factory() as session:
                batches=[batch async for batch in fen_backup.export_batches(session,datetime(2020,1,1,tzinfo=timezone.utc))]
            assert len(batches)==1 and len(batches[0])==1
            await fen_backup.restore_batch(batches[0])
            assert await conn.fetchval('SELECT count(*) FROM fen_continuation WHERE fen_id=1')==1
            for bad in (1.5,float('nan'),float('inf')):
                try:
                    async with factory.begin() as session:
                        await stage_fen_results(session,[{'fen':'test-fen-a','score':bad,'next_moves':'e2e4'}],[])
                    raise AssertionError('Lossy score accepted')
                except ValueError:
                    pass
            async with factory.begin() as session:
                await _save_tablebase_batch(session,[{'fen':'test-fen-b','piece_count':3,'score':1000.0,
                    'next_moves':'a1a2','wdl_win':1000.0,'wdl_draw':0.0,'wdl_loss':0.0,
                    'tablebase_wdl':2,'tablebase_dtz':1}],[])
            assert await conn.fetchval('SELECT score FROM fen WHERE fen_id=2')==1000
            from chessism_api.operations.fen_backup.archive import validate_record
            async with factory() as session:
                all_records=[row for batch in [b async for b in fen_backup.export_batches(session)] for row in batch]
            for row in all_records:
                validate_record(row)
            await fen_backup.restore_batch(all_records)
            assert await conn.fetchval('SELECT tablebase_wdl FROM fen WHERE fen_id=2')==2
        print('PASS compact writes: concurrent retries, conflicting identity, stats CRUD, months, summaries, analysis, tablebase, FEN export/restore, strict integers',flush=True)
    finally:
        await engine.dispose()


async def main():
    if Path('/var/lib/postgresql/data/PG_VERSION').exists():
        raise RuntimeError('No live data may be mounted')
    root=Path(tempfile.mkdtemp(prefix='compact-db-',dir='/restore-test'))
    pgdata,socket=root/'pgdata',root/'socket'
    pgdata.mkdir();socket.mkdir()
    conn=None
    async def publish(*args,**kwargs):
        pass
    try:
        await restore._run_command_capture(str(Path(restore.PG_CTL).with_name('initdb')),'-D',str(pgdata),
            '--username=chessism_user','--auth=trust','--locale=C')
        await restore._run_command_capture(restore.PG_CTL,'-D',str(pgdata),'-l',str(root/'postgres.log'),'-w',
            '-o',restore._postgres_start_options(socket),'start')
        conn=await asyncpg.connect(host=str(socket),port=55432,user='chessism_user',database='postgres')
        await conn.execute('CREATE DATABASE chessism_db')
        await conn.close()
        conn=await asyncpg.connect(host=str(socket),port=55432,user='chessism_user',database='chessism_db')
        await fixture(conn)
        try:
            await migrate_private(conn,pgdata,publish,inject_failure=True)
            raise AssertionError('Rollback injection not reached')
        except RuntimeError as error:
            assert 'Injected' in str(error),str(error)
        assert await conn.fetchval("SELECT count(*) FROM information_schema.columns WHERE table_name='moves' AND column_name='id'")==3
        assert await conn.fetchval('SELECT score FROM fen WHERE fen_id=1')==15.0
        from scripts.compact_db_indexes import read_index,validate_index,uses_impact_index
        legacy_index=await read_index(conn)
        validate_index(legacy_index)
        assert legacy_index['value_type']=='double precision'
        await migrate_private(conn,pgdata,publish)
        validate_index(await read_index(conn),integer=True)
        import json
        async with conn.transaction():
            # A two-row fixture naturally prefers a sequential scan; disabling
            # it here proves index eligibility. The full-size retest does not.
            await conn.execute('SET LOCAL enable_seqscan=off')
            plan=json.loads(await conn.fetchval('''EXPLAIN (FORMAT JSON) SELECT fen FROM fen
                WHERE score IS NOT NULL ORDER BY (n_games * abs(score)) DESC,n_games DESC LIMIT 20'''))[0]['Plan']
            assert uses_impact_index(plan),plan
        assert await conn.fetchval('SELECT count(*) FROM fen_continuation')==2
        assert await conn.fetchval('SELECT id FROM fen_continuation WHERE rank=2')==1
        await exercise(socket,conn)
        # A schema+data logical round-trip is separate from the FEN export.
        dump=root/'compact.dump'
        await restore._run_command_capture('pg_dump','-Fc','-h',str(socket),'-p','55432','-U','chessism_user',
            '-d','chessism_db','-f',str(dump))
        await conn.execute('CREATE DATABASE compact_restored')
        await restore._run_command_capture('pg_restore','--exit-on-error','-h',str(socket),'-p','55432',
            '-U','chessism_user','-d','compact_restored',str(dump))
        restored=await asyncpg.connect(host=str(socket),port=55432,user='chessism_user',database='compact_restored')
        try:
            validate_index(await read_index(restored),integer=True)
            assert await restored.fetchval('SELECT score FROM fen WHERE fen_id=2')==1000
            assert await restored.fetchval("SELECT chess_blitz_last_rating FROM chessism_reads.player_stats WHERE player_name='white'")==2010
            assert await restored.fetchval('SELECT count(*) FROM chessism_archive.moves')==1
        finally:
            await restored.close()
        print('PASS migration transaction rollback and compressed dump/restore; live database untouched',flush=True)
    finally:
        if conn:
            await conn.close()
        await restore._stop_restored_postgres(pgdata)


if __name__=='__main__':
    asyncio.run(main())
