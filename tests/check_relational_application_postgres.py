async def setup(conn, pgdata):
    await conn.execute(FIXTURE)
    await conn.execute('''ALTER TABLE player ADD COLUMN deleted_at timestamptz;
        ALTER TABLE fen ALTER COLUMN fen_id SET NOT NULL;
        ALTER TABLE fen ALTER COLUMN fen_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 2000);
        ALTER TABLE fen ADD COLUMN n_games bigint NOT NULL DEFAULT 0,
            ADD COLUMN moves_counter varchar NOT NULL DEFAULT '',ADD COLUMN piece_count integer,
            ADD COLUMN wdl_win float8, ADD COLUMN wdl_draw float8,ADD COLUMN wdl_loss float8,
            ADD COLUMN analysis_source varchar,ADD COLUMN tablebase_wdl integer,
            ADD COLUMN tablebase_dtz integer,ADD COLUMN analyzed_at timestamptz;
        CREATE TABLE fen_continuation(id serial PRIMARY KEY,fen_id bigint REFERENCES fen(fen_id),
            rank integer,move varchar,score float8,UNIQUE(fen_id,rank));
        ALTER TABLE fen RENAME CONSTRAINT fen_fen_id_key TO uq_fen_fen_id;
        ALTER TABLE fen_continuation ALTER COLUMN fen_id SET NOT NULL;
        ALTER TABLE fen_continuation RENAME CONSTRAINT fen_continuation_fen_id_rank_key TO uq_fen_continuation_fen_id_rank;
        ALTER TABLE fen_continuation RENAME CONSTRAINT fen_continuation_fen_id_fkey TO fk_fen_continuation_fen_id;
        ALTER TABLE game_player_engine_summary ADD COLUMN own_move_cp_gain float8,
            ADD COLUMN game_efficiency float8,ADD COLUMN mean_win_percent_loss float8,
            ADD COLUMN median_win_percent_loss float8,ADD COLUMN blunder_count integer,
            ADD COLUMN mate_for_positions integer,ADD COLUMN mate_against_positions integer,
            ADD COLUMN final_player_cp float8;
        CREATE TABLE months(player_name varchar,year integer,month integer,n_games integer,
            PRIMARY KEY(player_name,year,month));
        CREATE TABLE no_moves_games(game_id bigint PRIMARY KEY,played_at timestamptz NOT NULL);
    ''')
    await prepare_reference(conn,pgdata)
    async def publish(*args, **kwargs):
        pass
    await build_candidate(conn,pgdata,publish)
    await conn.execute(f'''CREATE TABLE {C}.moves (LIKE public.moves INCLUDING STORAGE);
        ALTER TABLE {C}.moves ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        INSERT INTO {C}.moves SELECT m.* FROM public.moves m JOIN {C}.game g ON g.link=m.link;
        ALTER TABLE {C}.moves ADD PRIMARY KEY(id),ADD UNIQUE(link,n_move),
            ADD FOREIGN KEY(link) REFERENCES {C}.game(link) ON DELETE CASCADE;
        SELECT setval(pg_get_serial_sequence('{C}.moves','id'),100,true);
        ALTER TABLE {A}.moves ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        SELECT setval(pg_get_serial_sequence('{A}.moves','id'),100,true);
        CREATE OR REPLACE VIEW {V}.moves AS SELECT * FROM {C}.moves;
    ''')


async def check_application(engine, conn):
    from chessism_api.database import ask_db, db_interface
    from chessism_api.database.models import Fen, GameFenAssociation
    from chessism_api.database.db_interface import DBInterface
    from chessism_api.operations import player_game_scores, player_salience, player_salience_calculation, player_deletion, home_summary
    from chessism_api.operations.ingestion_pipeline import game_repository, fen_repository
    from chessism_api.operations.ingestion_pipeline.fen_core import process_single_game_sync, aggregate_fen_data
    from chessism_api.operations.fen_results import stage_fen_results
    layout = RelationalStorage(C,A,V)
    factory = sessionmaker(engine,class_=AsyncSession,expire_on_commit=False,info={SESSION_KEY:layout})
    async with engine.connect() as connection:
        await require_storage_contract(connection,layout)
    bundle = fixture_bundle()

    async def ingest(selected=LINKS):
        await game_repository.insert_game_bundle(
            [r for r in bundle['games'] if r['link'] in selected],
            [r for r in bundle['moves'] if r['link'] in selected],
            [r for r in bundle['game_players'] if r['link'] in selected],
            [r for r in bundle['game_openings'] if r['link'] in selected], [],
            player_name=PLAYER, affected_months={(2025,1),(2025,2)}, affected_players={PLAYER,OTHER})

    with ExitStack() as patches:
        for module in (game_repository,fen_repository,ask_db,db_interface,player_game_scores,
                       player_salience,player_salience_calculation,player_deletion,home_summary):
            patches.enter_context(patch.object(module,'AsyncDBSession',factory))
        # Concurrent duplicates exercise the real transaction owner, bulk COPY,
        # native inserts, month ledger, and retry suppression together.
        await asyncio.wait_for(asyncio.gather(ingest(),ingest()),30)
        assert await conn.fetchval(f'SELECT count(*) FROM {C}.game WHERE link=ANY($1::bigint[])',LINKS)==3
        assert await conn.fetchval(f'SELECT count(*) FROM {C}.game_player WHERE game_link=ANY($1::bigint[])',LINKS)==6
        assert await conn.fetchval(f'SELECT count(*) FROM {A}.moves WHERE link=$1',LINKS[3])==4
        assert await conn.fetchval('SELECT n_games FROM months WHERE player_name=$1 AND month=1',PLAYER)==3
        assert await conn.fetchval('SELECT n_games FROM months WHERE player_name=$1 AND month=2',PLAYER)==0
        assert await game_repository._existing_game_links(set(LINKS)) == set(LINKS)
        print('PASS real ingestion: concurrent duplicates, numeric ownership, archive, exact month ledgers',flush=True)
        bad = dict(bundle['games'][0], link=-910000000099, eco='not-an-eco')
        try:
            await game_repository.insert_game_bundle([bad],[],[],[],[],player_name=PLAYER,
                affected_months={(2025,1)},affected_players={PLAYER})
        except ValueError:
            pass
        else:
            raise AssertionError('Expected invalid input to roll back')
        assert not await conn.fetchval(f'SELECT EXISTS(SELECT 1 FROM {C}.game WHERE link=$1)',bad['link'])
        assert await conn.fetchval('SELECT n_games FROM months WHERE player_name=$1 AND month=1',PLAYER)==3
        # A stale notification must use numeric ownership, not INSERT into a view.
        await conn.execute(f'UPDATE {C}.player SET joined=1 WHERE player_name=ANY($1::text[])',[PLAYER,OTHER])
        async with factory() as session:
            assert await player_salience.mark_player_salience_stale([PLAYER,OTHER],game_links=LINKS[:3],session=session)==2
            await session.commit()
        assert await conn.fetchval(f'SELECT count(*) FROM {C}.player_salience_pending_game p JOIN {C}.game_player gp ON gp.id=p.game_player_id WHERE gp.game_link=ANY($1::bigint[])',LINKS)==6

        # Two real claimers must never extract the same game concurrently.
        async with factory() as first, factory() as second:
            one = await fen_repository.claim_games_needing_fens(first,2)
            two = await fen_repository.claim_games_needing_fens(second,2)
            assert one and two and not set(one)&set(two)
            await fen_repository.set_game_fen_state(first,one,processing=True)
            await first.commit()
            await second.rollback()
        await fen_repository.release_fen_processing_claims(one)

        all_fens = set()
        for link in LINKS[:3]:
            extracted,errors=process_single_game_sync((link,[r for r in bundle['moves'] if r['link']==link]))
            assert not errors,errors
            fens,associations=aggregate_fen_data(extracted)
            all_fens.update(r['fen'] for r in fens)
            async with factory() as session:
                await DBInterface(Fen).create_all_with_session(session,fens)
                await DBInterface(GameFenAssociation).create_all_with_session(session,associations)
                await DBInterface(GameFenAssociation).create_all_with_session(session,associations)
                await fen_repository.set_game_fen_state(session,[link],done=True,processing=False)
                await session.commit()
            assert await conn.fetchval(f'SELECT count(*) FROM {C}.game_fen_association WHERE game_link=$1',link)==len(extracted)
        await fen_repository.refresh_fen_occurrence_counts(list(all_fens))
        print('PASS real extraction: disjoint claims, numeric associations, duplicate retries',flush=True)
        assert (await ask_db.refresh_game_analysis_summary(tuple(LINKS[:3]),strict=True))['games']==3
        async with factory() as session:
            formatted=[{'fen':f,'score':0.0,'next_moves':'','wdl_win':0.1,'wdl_draw':0.8,'wdl_loss':0.1} for f in all_fens]
            await stage_fen_results(session,formatted,[])
            await session.commit()
        await asyncio.wait_for(asyncio.gather(
            ask_db.increment_game_analysis_summary_for_scored_fens(formatted),
            ask_db.increment_game_analysis_summary_for_scored_fens(formatted)),30)
        coverage=await conn.fetch(f'SELECT * FROM {C}.game_analysis_coverage WHERE link=ANY($1::bigint[])',LINKS)
        assert len(coverage)==3 and all(r['is_fully_analyzed'] and r['analyzed_positions']==r['total_positions'] and r['equal_positions']==r['total_positions'] for r in coverage)
        assert await conn.fetchval(f'SELECT count(*) FROM {C}.game_player_engine_summary s JOIN {C}.game_player gp ON gp.id=s.game_player_id WHERE gp.game_link=ANY($1::bigint[])',LINKS)==6
        print('PASS real local/cloud result writer: zero scores, concurrent coverage replay, native engine summaries',flush=True)
        calculated = await player_salience_calculation.calculate_player_salience(PLAYER)
        assert calculated['status']=='ready' and calculated['source_game_count']==3,calculated
        extra_link=-910000000008
        await game_repository.insert_game_bundle([dict(bundle['games'][0],link=extra_link)],
            [dict(r,link=extra_link) for r in bundle['moves'] if r['link']==LINKS[0]],[],[],[],
            player_name=PLAYER,affected_months={(2025,1)},affected_players={PLAYER,OTHER})
        extracted,errors=process_single_game_sync((extra_link,[dict(r,link=extra_link) for r in bundle['moves'] if r['link']==LINKS[0]]))
        fens,associations=aggregate_fen_data(extracted)
        async with factory() as session:
            await DBInterface(Fen).create_all_with_session(session,fens)
            await DBInterface(GameFenAssociation).create_all_with_session(session,associations)
            await fen_repository.set_game_fen_state(session,[extra_link],done=True,processing=False)
            await session.commit()
        calculated = await player_salience_calculation.calculate_player_salience(PLAYER)
        assert calculated['calculation']=='incremental' and calculated['source_game_count']==4,calculated
        query=f'''SELECT s.salience,s.weighted_numerator,s.depth_weight_sum,s.position_occurrence_count,s.unique_position_count
            FROM {C}.game_player_salience s JOIN {C}.game_player gp ON gp.id=s.game_player_id
            JOIN {C}.player p ON p.id=gp.player_id WHERE p.player_name=$1 ORDER BY gp.game_link'''
        incremental=await conn.fetch(query,PLAYER)
        recalculated=await player_salience_calculation.calculate_player_salience(PLAYER)
        full=await conn.fetch(query,PLAYER)
        import math
        assert len(full)==len(incremental)==4
        assert all(math.isclose(float(a),float(b),rel_tol=1e-12,abs_tol=1e-12)
                   for before,after in zip(incremental,full) for a,b in zip(before,after))
        assert recalculated['status']=='ready'
        print('PASS real salience: native full, incremental and replay calculations match',flush=True)
        from chessism_api.operations.matrix_constructor.config import normalize_matrix_config
        from chessism_api.operations.matrix_constructor.queries import matrix_sql
        async with factory() as session:
            config=normalize_matrix_config({'row_type':'game','feature_columns':['average_abs_score'],
                'filters':{'players':[PLAYER],'max_rows':10}})
            count_sql,select_sql,params=matrix_sql(config)
            matrix=list((await session.execute(text(select_sql),params)).mappings())
            assert len(matrix)==4 and all(r['average_abs_score']==0 for r in matrix),matrix
            config=normalize_matrix_config({'row_type':'game_player','feature_columns':['rating','accuracy','game_salience'],
                'filters':{'players':[PLAYER],'max_rows':10}})
            _,select_sql,params=matrix_sql(config)
            assert len((await session.execute(text(select_sql),params)).all())==4
        page=await ask_db.get_scored_game_analysis_page()
        assert page['total']>=3 and all('avg_abs_score' in row for row in page['rows'])
        print('PASS real read consumers: saved matrix metrics, player salience matrix and scored-game page',flush=True)
        # Build only missing global-cache tables, inside the disposable layout.
        from chessism_api.database.models import Base
        async with engine.begin() as connection:
            connection=await connection.execution_options(schema_translate_map={None:C})
            names=('home_summary_source','home_titled_summary','home_titled_player_summary',
                   'database_summary','fen_pipeline_summary','scored_position_summary','main_character_mode_summary')
            await connection.run_sync(lambda sync:Base.metadata.create_all(sync,tables=[Base.metadata.tables[n] for n in names]))
            await connection.execute(text("INSERT INTO home_summary_source(id,revision) VALUES(1,1)"))
            from chessism_api.database.home_summary_schema import install_relational_home_triggers
            await install_relational_home_triggers(connection,layout)
        home=await home_summary.run_home_summary_refresh({})
        assert home['titled_games']==2,home # Neither archived Alice game belongs in the active count.
        await ask_db.refresh_database_summary_game_counts()
        await ask_db.refresh_fen_pipeline_summary()
        await ask_db.refresh_main_character_mode_summary_for_players({PLAYER,OTHER})
        await ask_db.refresh_scored_position_summary()
        await ask_db.sync_game_analytics_projection(tuple(LINKS[:3]))
        await ask_db.sync_game_analytics_projection(tuple(LINKS[:3]))
        assert await conn.fetchval(f'SELECT count(*) FROM {C}.game_player WHERE game_link=ANY($1::bigint[])',LINKS)==6
        print('PASS real global summaries: homepage, database counts, FEN pipeline, player modes, scored positions',flush=True)
        async with factory() as session:
            contract=await describe_contract(session,layout)
        assert (await validate_backup_contract(engine.url,contract))['schema_matches']
        bad_contract=dict(contract,columns=contract['columns'][:-1])
        try:
            await validate_backup_contract(engine.url,bad_contract)
        except RuntimeError:
            pass
        else:
            raise AssertionError('Restore validation accepted different columns')
        print('PASS backup contracts: normalized columns/constraints/views checked; mismatched manifest rejected',flush=True)
        # Only exclusive games may be removed; scores and typed archive survive.
        assert await player_deletion._delete_exclusive_game_batch(PLAYER,LINKS[:3])==0
        await conn.execute(f'UPDATE {C}.player SET joined=0 WHERE player_name=$1',OTHER)
        scored_before=await conn.fetchval('SELECT count(*) FROM fen WHERE score IS NOT NULL')
        assert await player_deletion._delete_exclusive_game_batch(PLAYER,[LINKS[0]])==1
        assert await player_deletion._delete_exclusive_game_batch(PLAYER,[LINKS[0]])==0
        assert await conn.fetchval('SELECT count(*) FROM fen WHERE score IS NOT NULL')==scored_before
        assert await conn.fetchval(f'SELECT count(*) FROM {A}.game WHERE link=$1',LINKS[3])==1
        assert await conn.fetchval(f'SELECT count(*) FROM {C}.game_player WHERE game_link=$1',LINKS[0])==0
        print('PASS real deletion: shared-game protection, numeric cascades, FEN/analysis retention, replay',flush=True)
        # Cross the COPY batching boundary and measure actual application calls.
        # This is a bounded fixture throughput smoke test, not a full-size DB benchmark.
        import time
        bulk_games=[dict(bundle['games'][0],link=-920000000000-i) for i in range(2001)]
        bulk_moves=[dict(r,link=g['link']) for g in bulk_games for r in bundle['moves'] if r['link']==LINKS[0]]
        started=time.monotonic()
        for attempt in range(2):
            await game_repository.insert_game_bundle(bulk_games,bulk_moves,[],[],[],player_name=PLAYER,
                affected_months={(2025,1)},affected_players={PLAYER,OTHER})
        elapsed=time.monotonic()-started
        assert await conn.fetchval(f'SELECT count(*) FROM {C}.game WHERE link=ANY($1::bigint[])',[g['link'] for g in bulk_games])==2001
        assert await conn.fetchval(f'SELECT count(*) FROM {C}.moves WHERE link=ANY($1::bigint[])',[g['link'] for g in bulk_games])==8004
        print(f'PASS bounded bulk ingestion: 2,001 games / 8,004 moves plus replay in {elapsed:.3f}s',flush=True)
        assert await conn.fetchval('SELECT count(*) FROM public.game')==4
        assert await conn.fetchval('SELECT count(*) FROM public.game_player')==8
        print('PASS original game/player tables unchanged',flush=True)


async def main():
    import asyncpg
    base=Path('/restore-test/db-refactor-baseline-app-fixture')
    base.mkdir(mode=0o700)
    pgdata,socket=base/'pgdata',base/'socket'
    socket.mkdir(mode=0o700)
    pgctl='/usr/lib/postgresql/15/bin/pg_ctl'
    await command('/usr/lib/postgresql/15/bin/initdb','-D',str(pgdata),'-U','chessism_user','--auth-local=trust','--auth-host=reject')
    conn=engine=None
    contract=None
    try:
        await command(pgctl,'-D',str(pgdata),'-l',str(base/'postgres.log'),'-w','-o',
            f"-c listen_addresses='' -c port=55432 -c unix_socket_directories='{socket}'",'start')
        conn=await asyncpg.connect(host=str(socket),port=55432,user='chessism_user',database='postgres')
        await setup(conn,pgdata)
        engine=await create_relational_engine(URL.create('postgresql+asyncpg',username='chessism_user',
            database='postgres',port=55432,query={'host':str(socket)}),RelationalStorage(C,A,V))
        await check_application(engine,conn)
        async with engine.connect() as connection:
            contract=await describe_contract(connection,RelationalStorage(C,A,V))
        from scripts.run_db_refactor_write_validation import cloud_import_checks
        from chessism_api.operations import database_restore_tests as restore
        core_checks=await cloud_import_checks(conn,socket,base,restore)
        assert core_checks['passed']==4
        print('PASS four actual cloud-import transaction/receipt tests (separate empty private DB)',flush=True)
    finally:
        if engine: await engine.dispose()
        if conn: await conn.close()
        await command(pgctl,'-D',str(pgdata),'-m','fast','-w','stop')

    # Exercise the real manifest validator on a physical restored copy. This
    # remains an OFFLINE backup; it does not accept online WAL/UI orchestration.
    from scripts.db_refactor_roundtrip import OfflineRoundTrip
    from chessism_api.operations import database_restore_tests as restore
    token=uuid4().hex[:12]
    restored=Path('/restore-test')/('db-refactor-baseline-app-verify-'+token)/'pgdata'
    work=Path('/restore-test')/('db-refactor-acceptance-'+token)
    async def publish(*args, **kwargs): pass
    roundtrip=OfflineRoundTrip(pgdata,socket,work,restored,publish,{})
    roundtrip.prepare()
    await roundtrip.run()
    restored_socket=restored.parent/'socket'
    await command(pgctl,'-D',str(restored),'-l',str(restored.parent/'postgres.log'),'-w','-o',
        f"-c listen_addresses='' -c port=55432 -c unix_socket_directories='{restored_socket}'",'start')
    try:
        manifest={'schema_version':7,'fen_identity_version':'numeric_v2',
                  'fen_reference_version':'relational_v2','relational_storage':contract}
        with patch.object(restore,'RESTORE_DATABASE','postgres'):
            result=await restore._validate_fen_identity(restored_socket,manifest)
        assert result['references']['schema_matches']
        print('PASS physical backup/restore: real v7 manifest validator accepted restored normalized storage',flush=True)
    finally:
        await command(pgctl,'-D',str(restored),'-m','fast','-w','stop')


if __name__=='__main__':
    asyncio.run(main())
