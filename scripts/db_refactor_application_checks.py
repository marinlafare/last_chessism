TIMESTAMP_RESPONSES = frozenset(('get_player_behavioural_activity','get_player_behavioural_ratings',
                               'get_player_engine_insights','get_player_playing_patterns'))


def comparable_response(method, value):
    """Exclude exactly the documented wall-clock metadata, nothing else.

    Still check that a timezone-aware timestamp was emitted. All actual data,
    nested timestamps, numeric types and array ordering stay in the hash.
    """
    if method not in TIMESTAMP_RESPONSES:
        return value
    if not isinstance(value,dict) or not isinstance(value.get('generated_at'),str):
        raise ValueError('Expected response generation timestamp')
    stamp=datetime.fromisoformat(value['generated_at'])
    if stamp.tzinfo is None or stamp.utcoffset() is None:
        raise ValueError('Response generation timestamp must have a timezone')
    return {key:item for key,item in value.items() if key!='generated_at'}


def response_differences(left, right, *, limit=20):
    """Record paths/types only; never dump a large/private response into logs."""
    differences=[]
    def visit(a,b,path):
        if len(differences)>=limit:
            return
        if type(a) is not type(b):
            differences.append({'path':path,'kind':'type','reference':type(a).__name__,'candidate':type(b).__name__})
        elif isinstance(a,dict):
            for key in sorted(a.keys()|b.keys()):
                if key not in a or key not in b:
                    differences.append({'path':path+'.'+key,'kind':'missing_key'})
                else:
                    visit(a[key],b[key],path+'.'+key)
                if len(differences)>=limit:
                    break
        elif isinstance(a,(list,tuple)):
            if len(a)!=len(b):
                differences.append({'path':path,'kind':'length','reference':len(a),'candidate':len(b)})
            for index,(x,y) in enumerate(zip(a,b)):
                visit(x,y,f'{path}[{index}]')
                if len(differences)>=limit:
                    break
        elif a!=b:
            differences.append({'path':path,'kind':'value'})
    visit(left,right,'$')
    return differences


def factory_for(socket, *, normalized, database='chessism_db', readonly=False):
    layout = RelationalStorage(C, A, V)
    settings = {'search_path': layout.search_path if normalized else f'{R},public',
                'statement_timeout': '120000', 'application_name': 'isolated-app-rehearsal'}
    if readonly:
        settings['default_transaction_read_only'] = 'on'
    engine = create_async_engine(URL.create('postgresql+asyncpg', username='chessism_user',
        database=database, port=55432, query={'host': str(socket)}),
        connect_args={'server_settings': settings})
    return engine, sessionmaker(engine, class_=AsyncSession, expire_on_commit=False,
        info={SESSION_KEY: layout} if normalized else {})


async def prepare_application_copy(conn, pgdata, publish):
    """Complete the experimental shadow layout; NEVER promotes public tables."""
    await guard(conn, pgdata)
    if await conn.fetchval(f"SELECT to_regclass('{C}.moves') IS NOT NULL"):
        raise RuntimeError('Application rehearsal requires an unused restored copy')
    async with conn.transaction():
        await conn.execute("SET LOCAL statement_timeout='2h'")
        await publish('copying_application_moves')
        await conn.execute(f'''CREATE TABLE {C}.moves (LIKE public.moves INCLUDING STORAGE);
            ALTER TABLE {C}.moves ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            INSERT INTO {C}.moves SELECT m.* FROM public.moves m JOIN {C}.game g ON g.link=m.link;
            ALTER TABLE {C}.moves ADD PRIMARY KEY(id),ADD UNIQUE(link,n_move),
                ADD FOREIGN KEY(link) REFERENCES {C}.game(link) ON DELETE CASCADE;
            ALTER TABLE {A}.moves ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            CREATE OR REPLACE VIEW {V}.moves AS SELECT * FROM {C}.moves;
            ANALYZE {C}.moves;''')
        for schema in (C, A):
            await preserve_sequence(conn, 'public', schema, 'moves')
        # Month-ledger inserts must reference the numeric layout's player name
        # unique key, not the retained legacy player table. Give the rehearsal
        # its own ledger and sequence; never bypass the real foreign key.
        await publish('preparing_application_month_ledger')
        await conn.execute(f'''CREATE TABLE {C}.months
            (LIKE public.months INCLUDING STORAGE INCLUDING CONSTRAINTS INCLUDING INDEXES);
            ALTER TABLE {C}.months ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            INSERT INTO {C}.months SELECT * FROM public.months;
            ALTER TABLE {C}.months ADD FOREIGN KEY(player_name) REFERENCES {C}.player(player_name);''')
        await preserve_sequence(conn, 'public', C, 'months')


def read_cases(players):
    from chessism_api.database import ask_db
    from chessism_api.operations import player_analytics, player_hero_analytics
    result = []
    for player in players:
        name, cohort = player['player_name'], player['cohort']
        for method in ('get_player_games_page', 'get_player_game_summary',
                       'get_player_performance_summary', 'get_player_game_averages',
                       'get_player_termination_stats'):
            result.append((cohort + '/' + method, ask_db, method, (name,)))
        for method in ('get_player_behavioural_activity', 'get_player_behavioural_ratings'):
            result.append((cohort + '/' + method, player_hero_analytics, method, (name,)))
        filters = player_analytics.normalize_player_analytics_filters(name, 'all', None, None)
        for method in ('get_player_engine_insights', 'get_player_playing_patterns'):
            result.append((cohort + '/' + method, player_analytics, method, (filters,)))
    return result


def rating_read_cases(players):
    """All modes and a bounded calendar year for every recorded cohort."""
    from chessism_api.operations import player_hero_analytics
    cases=[]
    method='get_player_behavioural_ratings'
    for player in players:
        name,cohort=player['player_name'],player['cohort']
        for mode in ('all','bullet','blitz','rapid'):
            cases.append((f'{cohort}/{method}/{mode}',player_hero_analytics,method,(name,mode)))
        year=player.get('year',2025)
        cases.append((f'{cohort}/{method}/calendar_year',player_hero_analytics,method,
                      (name,'all',date(year,1,1),date(year,12,31))))
    return cases


async def measure_application_reads(socket, players, publish, save, *, database='chessism_db', repeats=3,
                                    methods=None, capture_plans=False, ratings_only=False, analyze_plans=False):
    """Interleave old/new calls; preserve strict output values and array order."""
    from chessism_api.database import ask_db
    from chessism_api.operations import player_analytics, player_hero_analytics
    modules = (ask_db, player_analytics, player_hero_analytics)
    # The retained reference associations are text-keyed. Use the deployed
    # image's exact legacy analytics SQL there, not numeric SQL against columns
    # that never existed. Function entry points/payload formatting remain real.
    legacy_sql = {symbol: literal_sql('/app',symbol)
                  for symbol in ('ENGINE_INSIGHTS_SQL','PLAYING_PATTERNS_SQL')}
    engines, factories = [], []
    for normalized in (False, True):
        engine, factory = factory_for(socket, normalized=normalized, database=database, readonly=True)
        engines.append(engine)
        factories.append(factory)
    results = []
    cases = rating_read_cases(players) if ratings_only else read_cases(players)
    if methods is not None:
        cases=[case for case in cases if case[2] in methods]
    try:
        for index, (name, module, method, args) in enumerate(cases):
            await publish('measuring_application_reads', current_query=name,
                          queries_completed=index, queries_total=len(cases))
            samples = [[], []]
            hashes = [set(), set()]
            raw_hashes = [set(),set()]
            first_values = [None,None]
            variations = []
            plans = [[],[]]
            errors = []
            # Warmups are included in consistency checks, excluded from timing.
            for attempt in range(repeats + 1):
                for side in ((0, 1) if attempt % 2 == 0 else (1, 0)):
                    with ExitStack() as stack:
                        for target in modules:
                            stack.enter_context(patch.object(target, 'AsyncDBSession', factories[side]))
                        if side == 0:
                            for symbol, sql in legacy_sql.items():
                                stack.enter_context(patch.object(player_analytics,symbol,sql))
                        started = time.monotonic()
                        try:
                            statements=[]
                            def record_sql(connection,cursor,statement,parameters,context,many):
                                if statement.lstrip().upper().startswith(('SELECT','WITH')):
                                    statements.append((statement,parameters))
                            from sqlalchemy import event
                            if capture_plans and attempt==0:
                                event.listen(engines[side].sync_engine,'before_cursor_execute',record_sql)
                            try:
                                value = await asyncio.wait_for(getattr(module, method)(*args), 130)
                            finally:
                                if capture_plans and attempt==0:
                                    event.remove(engines[side].sync_engine,'before_cursor_execute',record_sql)
                            elapsed=time.monotonic()-started
                            if value is None:
                                raise RuntimeError('Application silently returned no result')
                            raw_hashes[side].add(digest(value))
                            comparable=comparable_response(method,value)
                            hashes[side].add(digest(comparable))
                            if first_values[side] is None:
                                first_values[side]=comparable
                            elif digest(first_values[side])!=digest(comparable):
                                variations.append({'side':side,'sample':attempt,
                                    'differences':response_differences(first_values[side],comparable)})
                            if attempt:
                                samples[side].append(elapsed)
                            if capture_plans and attempt==0:
                                async with engines[side].connect() as connection:
                                    driver=(await connection.get_raw_connection()).driver_connection
                                    for statement,parameters in statements:
                                        explain_options='ANALYZE, BUFFERS, TIMING OFF, FORMAT JSON, SETTINGS' if analyze_plans else 'FORMAT JSON, SETTINGS'
                                        plan=await driver.fetchval('EXPLAIN ('+explain_options+') '+statement,*parameters)
                                        import json
                                        # SQLAlchemy registers asyncpg JSON codecs, so
                                        # this connection can return an already-decoded plan.
                                        if isinstance(plan,(str,bytes,bytearray)):
                                            plan=json.loads(plan)
                                        if not isinstance(plan,list):
                                            raise TypeError('Unexpected EXPLAIN JSON shape')
                                        plans[side].append({'sql':statement,'plan':plan,'analyzed':analyze_plans})
                        except Exception as error:
                            errors.append({'side': side, 'type': type(error).__name__})
                if errors:
                    break
            medians = [statistics.median(s) if s else None for s in samples]
            match = not errors and len(hashes[0]) == len(hashes[1]) == 1 and hashes[0] == hashes[1]
            slower = bool(all(v is not None for v in medians) and
                          medians[1] > medians[0] * 1.20 and medians[1] - medians[0] > .005)
            results.append({'name': name, 'matches': match, 'slowdown': slower,
                'reference_seconds': medians[0], 'candidate_seconds': medians[1],
                'samples': samples, 'hashes': [sorted(h) for h in hashes], 'errors': errors,
                'raw_hashes':[sorted(h) for h in raw_hashes],
                'excluded_metadata':['generated_at'] if method in TIMESTAMP_RESPONSES else [],
                'differences':response_differences(*first_values), 'within_side_variations':variations,
                'plans':plans})
            save(results)
        return results
    finally:
        for engine in engines:
            await engine.dispose()


async def application_writes(conn, socket, publish, *, database='chessism_db'):
    """Bounded committed probes in the disposable copy, not the retained source."""
    from scripts.db_refactor_write_checks import fixture_bundle, PLAYER, OTHER, LINKS
    from chessism_api.database import ask_db
    from chessism_api.operations.ingestion_pipeline import game_repository
    from chessism_api.operations import player_game_scores, player_salience, player_salience_calculation
    engine, factory = factory_for(socket, normalized=True, database=database)
    bundle = fixture_bundle()
    games = [dict(bundle['games'][0], link=-920000000000-i) for i in range(2001)]
    moves = [dict(row, link=game['link']) for game in games
             for row in bundle['moves'] if row['link'] == LINKS[0]]
    ids = [g['link'] for g in games]
    if await conn.fetchval(f'SELECT EXISTS(SELECT 1 FROM {C}.game WHERE link=ANY($1::bigint[]))', ids+LINKS):
        raise RuntimeError('Reserved rehearsal game identities already exist')
    report = {}
    try:
        with ExitStack() as stack:
            for module in (game_repository, ask_db, player_game_scores, player_salience, player_salience_calculation):
                stack.enter_context(patch.object(module, 'AsyncDBSession', factory))
            await publish('testing_application_bulk_ingestion', games_total=2001)
            async def insert():
                await game_repository.insert_game_bundle(games, moves, [], [], [],
                    player_name=PLAYER, affected_months={(2025,1)}, affected_players={PLAYER,OTHER})
            started = time.monotonic()
            await asyncio.wait_for(asyncio.gather(insert(), insert()), 600)
            assert await conn.fetchval(f'SELECT count(*) FROM {C}.game WHERE link=ANY($1::bigint[])',ids) == 2001
            assert await conn.fetchval(f'SELECT count(*) FROM {C}.moves WHERE link=ANY($1::bigint[])',ids) == 8004
            assert await conn.fetchval(f'SELECT count(*) FROM {C}.game_player WHERE game_link=ANY($1::bigint[])',ids) == 4002
            report['bulk_ingestion'] = {'games':2001, 'moves':8004, 'concurrent_replays':2,
                                        'seconds':time.monotonic()-started}
            await publish('testing_application_archive')
            archived = bundle['games'][3]
            for _ in range(2):
                await game_repository.insert_game_bundle([archived],
                    [r for r in bundle['moves'] if r['link']==LINKS[3]], [], [], [],
                    player_name=PLAYER, affected_months={(2025,1)}, affected_players={PLAYER,OTHER})
            assert await conn.fetchval(f'SELECT count(*) FROM {A}.moves WHERE link=$1',LINKS[3]) == 4
            assert not await conn.fetchval(f'SELECT EXISTS(SELECT 1 FROM {C}.game WHERE link=$1)',LINKS[3])
            report['typed_archive_retry'] = 'passed'
            await publish('testing_application_coverage')
            # Recount bounded, pre-existing games without overwriting real scores.
            links = list(await conn.fetchval(f'SELECT array_agg(link) FROM (SELECT link FROM {C}.game WHERE fens_done ORDER BY link DESC LIMIT 100) s'))
            started = time.monotonic()
            await asyncio.gather(*(ask_db.refresh_game_analysis_summary(tuple(links),strict=True) for _ in range(2)))
            bad = await conn.fetchval(f'''SELECT count(*) FROM {C}.game_analysis_coverage
                WHERE link=ANY($1::bigint[]) AND (total_positions<>analyzed_positions+unscored_positions
                OR is_fully_analyzed<>(total_positions>0 AND unscored_positions=0))''',links)
            assert bad == 0
            report['concurrent_coverage'] = {'games':len(links), 'seconds':time.monotonic()-started}
            await publish('testing_application_salience', current_player='magnuscarlsen')
            started = time.monotonic()
            result = await player_salience_calculation.calculate_player_salience('magnuscarlsen')
            assert result['status'] in ('ready', 'stale') and result['source_game_count'] > 1000, result
            report['real_player_salience'] = {'seconds':time.monotonic()-started,
                'status':result['status'], 'games':result['source_game_count']}
            # No changes to any FEN score or original public game row by these probes.
        return report
    finally:
        await engine.dispose()
