"""Explicit normalized write contracts for the PRIVATE candidate rehearsal.

Not an application deployment or automatic schema detector. Callers must open
the store through the private-target guard and own the transaction. Existing
application orchestration is deliberately not redirected to these tables.
"""
from scripts.db_refactor_candidate import C, A, START, guard, qi


def standard_game(row):
    setup = ' '.join(str(row.get('initial_setup') or '').split())
    return row.get('rules') == 'chess' and setup in ('', START, START+' 0 1')


def short_eco(value):
    prefix = 'https://www.chess.com/openings/'
    if value == 'no_eco':
        return value
    if not isinstance(value, str) or not value.startswith(prefix):
        raise ValueError('Unexpected ECO format; refusing lossy conversion')
    return value[len(prefix):]


class CandidateStore:
    def __init__(self, conn, token):
        if token is not _PRIVATE:
            raise RuntimeError('Use CandidateStore.open with the private database guard')
        self.conn = conn
        self.catalog = {}

    @classmethod
    async def open(cls, conn, pgdata):
        await guard(conn, pgdata)
        if not conn.is_in_transaction():
            raise RuntimeError('Candidate writes require an already active caller transaction')
        return cls(conn, _PRIVATE)

    async def prepare_probe_moves(self):
        # The read rehearsal shares public.moves. Probe writes need a real table
        # referencing candidate games, never an INSERT into the read-only view.
        await self.conn.execute(f'''CREATE TABLE {C}.moves (LIKE public.moves INCLUDING STORAGE);
            ALTER TABLE {C}.moves ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            ALTER TABLE {C}.moves ADD PRIMARY KEY(id), ADD UNIQUE(link,n_move),
                ADD FOREIGN KEY(link) REFERENCES {C}.game(link) ON DELETE CASCADE;
            ALTER TABLE {A}.moves ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;''')
        await self.conn.fetchval(f'''SELECT setval(pg_get_serial_sequence('{A}.moves','id'),
            GREATEST(COALESCE((SELECT max(id) FROM {A}.moves),0)+1,1),false)''')

    async def insert(self, schema, table, row, conflict, returning=None):
        allowed = {(C,t) for t in ('player','game_mode','game','moves','game_player','opening_sequence',
                   'game_opening','game_fen_association')} | {(A,'game'),(A,'moves'),('public','fen')}
        if (schema,table) not in allowed:
            raise ValueError('Table is outside the explicit rehearsal writer contract')
        cache_key = schema,table
        if cache_key not in self.catalog:
            self.catalog[cache_key] = {r['column_name']:r['data_type'] for r in await self.conn.fetch('''
                SELECT column_name,data_type FROM information_schema.columns
                WHERE table_schema=$1 AND table_name=$2''',schema,table)}
        columns = self.catalog[cache_key]
        if not row or not set(row) <= columns.keys() or not set(conflict) <= columns.keys():
            raise ValueError('Unknown/missing write fields')
        fields,values = [],[]
        for field,value in row.items():
            if columns[field] in ('integer','bigint','smallint') and isinstance(value,float):
                if not value.is_integer():
                    raise ValueError('Refusing to truncate a fractional integer field')
                value = int(value)
            fields.append(qi(field))
            values.append(value)
        if returning and returning not in columns:
            raise ValueError('Invalid return field')
        query = (f'INSERT INTO {schema}.{table} ({",".join(fields)}) VALUES '
                 f'({",".join("$"+str(i+1) for i in range(len(values)))}) '
                 f'ON CONFLICT ({",".join(map(qi,conflict))}) DO NOTHING')
        if returning:
            return await self.conn.fetchval(query+' RETURNING '+qi(returning),*values)
        return await self.conn.execute(query,*values)

    async def ingest(self, games, moves, openings):
        """Route variants, insert numeric owners, and atomically deduplicate bundles."""
        inserted = {'standard':[], 'archived':[]}
        for original in games:
            row = dict(original, fens_processing=False)
            if not standard_game(row):
                if await self.conn.fetchval(f'SELECT EXISTS(SELECT 1 FROM {C}.game WHERE link=$1)',row['link']):
                    raise ValueError('Game identity is already in the active corpus')
                link = await self.insert(A,'game',row,('link',),'link')
                if link is not None:
                    for move in moves:
                        if move['link']==link:
                            await self.insert(A,'moves',move,('link','n_move'))
                    inserted['archived'].append(link)
                continue
            if await self.conn.fetchval(f'SELECT EXISTS(SELECT 1 FROM {A}.game WHERE link=$1)',row['link']):
                raise ValueError('Game identity is already in the archive')
            players = {}
            for side in ('white','black'):
                name = row.pop(side)
                await self.insert(C,'player',{'player_name':name,'joined':0},('player_name',))
                players[side] = await self.conn.fetchval(f'SELECT id FROM {C}.player WHERE player_name=$1',name)
                row[side+'_player_id'] = players[side]
            mode = row.pop('mode')
            row['mode_id'] = None
            if mode is not None:
                await self.insert(C,'game_mode',{'name':mode},('name',))
                row['mode_id'] = await self.conn.fetchval(f'SELECT id FROM {C}.game_mode WHERE name=$1',mode)
            row.pop('rules'); row.pop('initial_setup',None)
            row['eco'] = short_eco(row['eco'])
            row['fens_done'] = False
            link = await self.insert(C,'game',row,('link',),'link')
            if link is None:
                continue
            for side in ('white','black'):
                await self.insert(C,'game_player',{'game_link':link,'player_id':players[side],
                    'is_white':side=='white'},('game_link','is_white'))
            for move in moves:
                if move['link']==link:
                    await self.insert(C,'moves',move,('link','n_move'))
            for opening in openings:
                if opening['link']==link:
                    await self.insert(C,'opening_sequence',{'opening':opening['opening']},('opening',))
                    identity = await self.conn.fetchval(f'SELECT id FROM {C}.opening_sequence WHERE opening=$1',opening['opening'])
                    await self.insert(C,'game_opening',{'link':link,'n_moves':opening['n_moves'],
                        'opening_id':identity},('link','n_moves'))
            inserted['standard'].append(link)
        return inserted

    async def associations(self, rows):
        from chessism_api.operations.ingestion_pipeline.fen_core import aggregate_fen_data
        fens, associations = aggregate_fen_data(rows)
        for fen in fens:
            # Existing canonical FENs/analyses must never be reset by ingestion.
            await self.insert('public','fen',fen,('fen',))
        identities = {r['fen']:r['fen_id'] for r in await self.conn.fetch(
            'SELECT fen,fen_id FROM public.fen WHERE fen=ANY($1::varchar[])',[r['fen'] for r in fens])}
        for row in associations:
            row = dict(row)
            row['fen_id'] = identities[row.pop('fen_fen')]
            await self.insert(C,'game_fen_association',row,('game_link','fen_id','n_move','move_color'))
        links = sorted({row['game_link'] for row in associations})
        await self.conn.execute(f'UPDATE {C}.game SET fens_done=true WHERE link=ANY($1::bigint[])',links)
        await self.conn.execute(f'''INSERT INTO {C}.player_salience_pending_game(game_player_id)
            SELECT id FROM {C}.game_player WHERE game_link=ANY($1::bigint[]) ON CONFLICT DO NOTHING''',links)
        return identities

    async def coverage(self, links):
        names = ['total_positions','analyzed_positions','unscored_positions','is_fully_analyzed',
                 'equal_positions','small_positions','clear_positions','decisive_positions','mate_positions','refreshed_at']
        await self.conn.execute(f'''DELETE FROM {C}.game_analysis_coverage c
            WHERE link=ANY($1::bigint[]) AND NOT EXISTS(
                SELECT 1 FROM {C}.game_fen_association a WHERE a.game_link=c.link)''',links)
        await self.conn.execute(f'''INSERT INTO {C}.game_analysis_coverage(link,{','.join(names)})
            SELECT a.game_link,count(*)::int,count(f.score)::int,
                (count(*)-count(f.score))::int,count(f.score)=count(*),
                count(*) FILTER(WHERE abs(f.score)<50)::int,
                count(*) FILTER(WHERE abs(f.score)>=50 AND abs(f.score)<150)::int,
                count(*) FILTER(WHERE abs(f.score)>=150 AND abs(f.score)<300)::int,
                count(*) FILTER(WHERE abs(f.score)>=300 AND abs(f.score)<9000)::int,
                count(*) FILTER(WHERE abs(f.score)>=9000)::int,CURRENT_TIMESTAMP
            FROM {C}.game_fen_association a JOIN public.fen f ON f.fen_id=a.fen_id
            WHERE a.game_link=ANY($1::bigint[]) GROUP BY a.game_link
            ON CONFLICT(link) DO UPDATE SET {','.join(n+'=EXCLUDED.'+n for n in names)}''',links)


_PRIVATE = object()
